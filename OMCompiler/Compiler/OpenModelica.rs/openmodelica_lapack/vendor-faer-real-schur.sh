#!/bin/sh
# Regenerate src/faer_real_schur.rs from faer's own real_schur.rs.
#
# faer keeps `linalg::evd::schur::real_schur` `pub(crate)`, so `multishift_qr`
# — whose signature is already LAPACK's DLAQR0 — cannot be called from outside
# the crate. Upstream has an issue open and wants to refactor rather than widen
# the visibility, so this copy is long-lived: re-run this script on a faer bump
# instead of re-deriving the edits by hand.
#
#   ./vendor-faer-real-schur.sh [path/to/faer/src/linalg/evd/schur/real_schur.rs]
#
# With no argument it takes the version cargo resolved, from the registry.
# Afterwards: `cargo test --features reference-lapack,faer-backend`, whose
# dgees/dhseqr/dgeev tests compare against the system LAPACK.
#
# Every edit below is mechanical. Nothing this file needs is genuinely private
# except `stack_mat!` (rebuilt from the public `temp_mat_zeroed`) and
# `ColMut::at_mut` (written as `&mut head[0]`).
set -e
cd "$(dirname "$0")"

want=$(sed -n 's/^name = "faer"$/faer/p;' Cargo.lock >/dev/null 2>&1 || true)
ver=$(awk '/^name = "faer"$/{getline; gsub(/[";]/,""); print $3}' Cargo.lock)
src=${1:-$(echo "$HOME"/.cargo/registry/src/*/faer-"$ver"/src/linalg/evd/schur/real_schur.rs)}
[ -f "$src" ] || { echo "no faer source at $src" >&2; exit 1; }
echo "vendoring from $src"

out=src/faer_real_schur.rs
{
cat <<EOF
//! faer $ver's \`src/linalg/evd/schur/real_schur.rs\`, verbatim apart from the
//! imports at the top and two accessors. **Generated by
//! \`vendor-faer-real-schur.sh\`** — re-run that on a faer bump rather than
//! editing this file.
//!
//! faer computes a real Schur form but keeps \`linalg::evd::schur::real_schur\`
//! \`pub(crate)\`, so \`multishift_qr\` — whose signature is already LAPACK's
//! \`DLAQR0\` — cannot be called from outside the crate, even though its
//! \`multishift_qr_scratch\` sizing function *is* exported. Upstream has an
//! issue open and intends to refactor rather than widen the visibility, so this
//! copy is here for the long run.
//!
//! What differs from the original, all mechanical:
//!   * the \`use\` block: every path it needs is public, reached via
//!     \`faer::{traits::{math_utils, ext}, linalg::{householder, jacobi, matmul,
//!     temp_mat_*, evd::hessenberg}, perm, zip, unzip}\`;
//!   * \`stack_mat!\`, faer's crate-private macro, rebuilt from the public
//!     \`temp_mat_zeroed\`;
//!   * \`head.at_mut(0)\` (a private accessor) written as \`&mut head[0]\`;
//!   * one \`assert!(all(..))\` split into plain asserts, so \`equator\` is not a
//!     dependency;
//!   * faer's own \`mod tests\` dropped.
EOF
sed -e '1,5d' "$src" | sed -e '1i\
#![allow(dead_code, unused_imports, non_snake_case, clippy::all)]\
use faer::prelude::*;\
use faer::linalg;\
use faer::linalg::householder::*;\
use faer::linalg::jacobi::JacobiRotation;\
use faer::linalg::matmul::matmul;\
use faer::linalg::evd::schur::SchurParams;\
use faer::dyn_stack::{MemStack, StackReq};\
use faer::{Par, Spec, Accum, Conj, ContiguousFwd, Shape, Stride, Unbind, unzip, zip};\
use faer::traits::{ComplexField, RealField};\
use faer::traits::math_utils::*;\
use faer::traits::ext::*;\
use faer::linalg::{temp_mat_uninit, temp_mat_scratch, temp_mat_zeroed};\
use faer::linalg::evd::hessenberg;\
use faer::mat::AsMatMut;\
use faer::{zip as z, unzip as uz};\
\
/// faer'"'"'s `stack_mat!` is crate-private; it is a fixed-size scratch matrix on\
/// the stack, which the public `temp_mat_zeroed` builds just as well.\
macro_rules! stack_mat {\
    ($name:ident, $m:expr, $n:expr, $A:expr, $N:expr, $T:ty $(,)?) => {\
        let mut __tmp = {\
            #[repr(align(64))]\
            struct __Col<T, const A: usize>([T; A]);\
            struct __Mat<T, const A: usize, const N: usize>([__Col<T, A>; N]);\
            core::mem::MaybeUninit::<__Mat<$T, $A, $N>>::uninit()\
        };\
        let __stack = MemStack::new_any(core::slice::from_mut(\&mut __tmp));\
        let mut $name = temp_mat_zeroed::<$T, _, _>($m, $n, __stack).0;\
        let mut $name = AsMatMut::as_mat_mut(\&mut $name);\
    };\
    ($name:ident, $m:expr, $n:expr, $T:ty $(,)?) => {\
        stack_mat!($name, $m, $n, $m, $n, $T)\
    };\
}' \
    -e 's|crate::perm::|faer::perm::|g' \
    -e 's|crate::linalg::temp_mat_zeroed|temp_mat_zeroed|g' \
    -e 's|use crate::linalg::evd::schur::multishift_qr_scratch;|use faer::linalg::evd::schur::multishift_qr_scratch;|' \
    -e 's|head\.at_mut(0)|\&mut head[0]|g' \
    -e 's|let (head, tail) = \(v[12]\)\.rb_mut()\.split_at_row_mut(1);|let (mut head, tail) = \1.rb_mut().split_at_row_mut(1);|'
} > "$out.tmp"

# faer's `assert!(all(..))` is equator syntax; plain asserts avoid the dependency.
python3 - "$out.tmp" <<'PY'
import sys, re
p = sys.argv[1]
s = open(p).read()
def split_all(m):
    body = m.group(1)
    parts = [x.strip() for x in body.split(',') if x.strip()]
    indent = '\t'
    return '\n'.join(f'{indent}assert!({x});' for x in parts)
s = re.sub(r'\tassert!\(all\(\n((?:\t\t[^\n]*\n)+?)\t\)\);', lambda m: split_all(m), s)
open(p, 'w').write(s)
PY

# Drop faer's own `mod tests`.
python3 - "$out.tmp" <<'PY'
import sys
p = sys.argv[1]
s = open(p).read()
i = s.rfind('#[cfg(test)]')
if i != -1:
    s = s[:i] + '// faer\'s own `mod tests` is dropped here; ours is in lib.rs.\n'
open(p, 'w').write(s)
PY

mv "$out.tmp" "$out"
echo "wrote $out ($(grep -c '' "$out") lines)"
