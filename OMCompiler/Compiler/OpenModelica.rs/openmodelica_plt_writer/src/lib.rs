//! Ptolemy (`.plt`) result-file writer for the wasm-jit simulation target.
//!
//! A port of `SimulationRuntime/c/simulation/results/simulation_result_plt.cpp`.
//! The file is a sequence of `DataSet:` blocks, one per variable, each holding
//! `actualPoints` lines of `"<time>, <value>"` formatted with C's `%.16g`.
//!
//! `no_std` + `alloc`, no wasm intrinsics and no I/O: [`write_plt`] produces the
//! whole file as a `Vec<u8>` and the caller writes it. One implementation is
//! shared by the host (VFS / disk) and the standalone `wasm32-wasip1` runtime's
//! `_start` (WASI), so the two `.plt` serializers cannot drift apart.

#![cfg_attr(not(test), no_std)]

extern crate alloc;

use alloc::string::{String, ToString};
use alloc::vec::Vec;
use alloc::format;

/// Negation of a stored value, mirroring the C `Neg` of the result signals.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Neg {
    None,
    Arith,
    Not,
}

/// How to read one result signal out of the run buffers, mirroring the C
/// `DataInfo` roles of the plt writer.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum PltKind {
    /// The time axis: column 0 of every row.
    Time,
    /// A column of the row-major `rows` trajectory (states, derivatives,
    /// real/integer/boolean algebraics).
    Column { col: u32, negate: Neg },
    /// A parameter: a constant read from `kept_params`, in signal order.
    Param { negate: Neg },
    /// A compile-time constant: the same value at every point.
    Const { value: f64 },
}

/// One result signal to emit as a `DataSet:` block.
#[derive(Clone, Copy, Debug)]
pub struct PltVar<'a> {
    pub name: &'a str,
    pub kind: PltKind,
}

/// C's `%.<p>g`: `p` significant digits, `%e` outside `[1e-4, 10^p)`, trailing
/// zeros and a bare decimal point trimmed.
fn format_g(v: f64, p: i32) -> String {
    if !v.is_finite() || v == 0.0 {
        return format!("{v}");
    }
    let exp = libm::floor(libm::log10(libm::fabs(v))) as i32;
    let trim = |s: String| -> String {
        if !s.contains('.') {
            return s;
        }
        s.trim_end_matches('0').trim_end_matches('.').to_string()
    };
    if exp < -4 || exp >= p {
        let m = trim(format!("{:.*}", (p - 1) as usize, v / libm::pow(10.0, exp as f64)));
        return format!("{m}e{}{:02}", if exp < 0 { '-' } else { '+' }, exp.abs());
    }
    trim(format!("{:.*}", (p - 1 - exp).max(0) as usize, v))
}

fn apply_negate(v: f64, negate: Neg) -> f64 {
    match negate {
        Neg::None => v,
        Neg::Arith => -v,
        Neg::Not => if v != 0.0 { 1.0 } else { 0.0 },
    }
}

/// Serialize the run into a Ptolemy `.plt` file.
///
/// `signals` are the kept result signals, in the order to emit them (the C
/// result order: the time signal first, then the variable/parameter/constant/
/// alias signals). `rows` is the row-major trajectory with `n_reals` columns
/// per row (column 0 is the time). `kept_params` holds the parameter values,
/// in the order of the `Param` signals within `signals`.
pub fn write_plt(signals: &[PltVar], rows: &[f64], n_reals: u32, kept_params: &[f64]) -> Vec<u8> {
    let n_reals = n_reals.max(1) as usize;
    let actual_points = rows.len() / n_reals;
    let num_vars = signals.len(); // one DataSet per signal (time included)

    let mut out = String::new();
    out.push_str("#Ptolemy Plot file, generated by OpenModelica\n");
    out.push_str(&format!("#NumberofVariables={num_vars}\n"));
    out.push_str(&format!("#IntervalSize={actual_points}\n"));
    out.push_str("TitleText: OpenModelica simulation plot\n");
    out.push_str("XLabel: t\n\n");

    let mut param_idx = 0usize;
    for sig in signals {
        out.push_str("DataSet: ");
        out.push_str(sig.name);
        out.push('\n');
        for i in 0..actual_points {
            let row = &rows[i * n_reals..(i + 1) * n_reals];
            let time = row[0];
            let val = match sig.kind {
                PltKind::Time => time,
                PltKind::Column { col, negate } => {
                    let c = (col as usize).min(row.len().saturating_sub(1));
                    apply_negate(row[c], negate)
                }
                PltKind::Param { negate } => {
                    let v = kept_params.get(param_idx).copied().unwrap_or(0.0);
                    param_idx += 1;
                    apply_negate(v, negate)
                }
                PltKind::Const { value } => value,
            };
            out.push_str(&format!("{}, {}\n", format_g(time, 16), format_g(val, 16)));
        }
        out.push('\n');
    }

    out.into_bytes()
}
