//! Susan's Rust backend: prints an elaborated template package (TplAbsyn's
//! `MMPackage`) as a Rust module, resolving everything the templates call or
//! match on through the interface index written by `susan-index`.
//!
//! Calling convention of the generated functions: `Tpl::Text` is passed by
//! value, Integer/Real/Boolean by copy, every other argument as `&T`; every
//! function returns `Result`.

use std::collections::{BTreeSet, HashMap, HashSet};
use std::fmt::Write as _;

use arcstr::ArcStr;
use metamodelica::{List, Ref};
use openmodelica_susan::TplAbsyn::{
    ASTDef, MMDeclaration, MMExp, MMPackage, MatchingExp, PathIdent, TemplPackage, TypeInfo, TypeSignature,
};
use openmodelica_susan_index::{ConstAccess, Index, Ty, TypeDef};
use openmodelica_tpl::Tpl;

type Typed = List<(ArcStr, Ref<TypeSignature>)>;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Mode {
    Owned,
    Copy,
    Borrowed,
}

#[derive(Clone, Debug)]
struct Param {
    ty: Ty,
    mode: Mode,
}

#[derive(Clone, Debug)]
struct Sig {
    rust: String,
    params: Vec<Param>,
    outs: Vec<Ty>,
    fallible: bool,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Kind {
    Owned,
    /// A reference into a matched value or a borrowed parameter.
    Ref,
}

#[derive(Clone, Debug)]
struct Var {
    ty: Ty,
    kind: Kind,
    /// Declared outside the loop the current statement runs in.
    outer: bool,
}

type Env = HashMap<String, Var>;

/// The shapes TplAbsyn gives a function body.
#[derive(PartialEq)]
enum Body {
    Statements,
    Match,
    ListLoop,
    ArrayLoop,
}

fn path_string(p: &PathIdent) -> String {
    match p {
        PathIdent::IDENT { ident } => ident.to_string(),
        PathIdent::PATH_IDENT { ident, path } => format!("{ident}.{}", path_string(path)),
    }
}

fn split_path(p: &PathIdent) -> (Option<String>, String) {
    let s = path_string(p);
    match s.rsplit_once('.') {
        Some((a, b)) => (Some(a.to_string()), b.to_string()),
        None => (None, s),
    }
}

const RUST_KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let",
    "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type",
    "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
];

fn ident(n: &str) -> String {
    match n {
        "self" | "Self" | "super" | "crate" => format!("{n}_"),
        _ if RUST_KEYWORDS.contains(&n) => format!("r#{n}"),
        _ => n.to_string(),
    }
}

fn rust_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => write!(out, "\\u{{{:x}}}", c as u32).unwrap(),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn contains_funcptr(t: &Ty) -> bool {
    match t {
        Ty::FuncPtr => true,
        Ty::Ref(t) | Ty::List(t) | Ty::Option(t) | Ty::Array(t) => contains_funcptr(t),
        Ty::Tuple(ts) | Ty::Generic(_, ts) => ts.iter().any(contains_funcptr),
        _ => false,
    }
}

const SOURCE_INFO_FIELDS: &[(&str, Ty)] = &[
    ("fileName", Ty::String),
    ("isReadOnly", Ty::Bool),
    ("lineNumberStart", Ty::Int),
    ("columnNumberStart", Ty::Int),
    ("lineNumberEnd", Ty::Int),
    ("columnNumberEnd", Ty::Int),
    ("lastModification", Ty::Real),
];

fn is_copy(t: &Ty) -> bool {
    matches!(t, Ty::Int | Ty::Real | Ty::F64 | Ty::Bool)
}

fn convention(t: &Ty) -> Mode {
    match t {
        Ty::Text => Mode::Owned,
        t if is_copy(t) => Mode::Copy,
        _ => Mode::Borrowed,
    }
}

fn interface_crate(interface: &str) -> String {
    match interface {
        "parser" => "openmodelica_ast".into(),
        i => format!("openmodelica_{i}"),
    }
}

fn annotation_interface(footer: &str) -> Option<String> {
    let key = "__OpenModelica_Interface=\"";
    let start = footer.find(key)? + key.len();
    let end = footer[start..].find('"')?;
    Some(footer[start..start + end].to_string())
}

struct Printer<'a> {
    idx: &'a Index,
    pkg: String,
    krate: String,
    /// Packages generated by Susan (a `.tpl` exists), with their crate.
    tpl_crates: HashMap<String, String>,
    uses: BTreeSet<String>,
    local_funs: HashMap<String, Sig>,
    local_consts: HashMap<String, Ty>,
    tpl_funs: HashMap<(String, String), Sig>,
    tpl_consts: HashMap<(String, String), Ty>,
    errors: Vec<String>,
    current: String,
}

impl<'a> Printer<'a> {
    fn err(&mut self, msg: String) -> String {
        self.errors.push(format!("{}: {msg}", self.current));
        format!("compile_error!({})", rust_string(&msg))
    }

    fn use_pkg(&mut self, pkg: &str) -> String {
        if pkg != self.pkg {
            self.uses.insert(pkg.to_string());
        }
        pkg.to_string()
    }

    fn named(&self, name: &str) -> Option<&'a TypeDef> {
        let (p, n) = name.rsplit_once('.')?;
        self.idx.packages.get(p)?.types.get(n)
    }

    /// The Rust-level type of a Susan type, boxing named types as the sources do.
    fn susan_ty(&mut self, t: &TypeSignature) -> Ty {
        match t {
            TypeSignature::STRING_TYPE => Ty::String,
            TypeSignature::TEXT_TYPE => Ty::Text,
            TypeSignature::STRING_TOKEN_TYPE => Ty::Ref(Box::new(Ty::Named("Tpl.StringToken".into()))),
            TypeSignature::INTEGER_TYPE => Ty::Int,
            TypeSignature::REAL_TYPE => Ty::Real,
            TypeSignature::BOOLEAN_TYPE => Ty::Bool,
            TypeSignature::LIST_TYPE { ofType } => Ty::List(Box::new(self.susan_ty(ofType))),
            TypeSignature::ARRAY_TYPE { ofType } => Ty::Array(Box::new(self.susan_ty(ofType))),
            TypeSignature::OPTION_TYPE { ofType } => Ty::Option(Box::new(self.susan_ty(ofType))),
            TypeSignature::TUPLE_TYPE { ofTypes } => Ty::Tuple(ofTypes.iter().map(|t| self.susan_ty(t)).collect()),
            TypeSignature::NAMED_TYPE { name } => {
                let n = path_string(name);
                match n.as_str() {
                    "Tpl.Text" | "Text" => return Ty::Text,
                    "builtin.SourceInfo" | "SourceInfo" => return Ty::SourceInfo,
                    "builtin.FuncPtr" => return Ty::FuncPtr,
                    _ => {}
                }
                match self.named(&n) {
                    Some(TypeDef::Alias(t)) if !contains_funcptr(t) => t.clone(),
                    // A function type has no spelling here; its alias has.
                    Some(TypeDef::Alias(_)) => Ty::Named(n),
                    Some(_) if self.idx.is_boxed(&n) => Ty::Ref(Box::new(Ty::Named(n))),
                    _ => Ty::Named(n),
                }
            }
            TypeSignature::UNRESOLVED_TYPE { reason } => {
                self.err(format!("unresolved type: {reason}"));
                Ty::Unit
            }
        }
    }

    fn type_path(&mut self, name: &str) -> String {
        let Some((p, n)) = name.rsplit_once('.') else {
            return name.to_string();
        };
        let p = p.to_string();
        let rust = match self.named(name) {
            Some(TypeDef::Union { rust, .. }) => rust.clone(),
            _ => n.to_string(),
        };
        let p = self.use_pkg(&p);
        format!("{p}::{rust}")
    }

    fn rust_ty(&mut self, t: &Ty) -> String {
        match t {
            Ty::Int => "i32".into(),
            Ty::Real => "metamodelica::Real".into(),
            Ty::F64 => "f64".into(),
            Ty::Bool => "bool".into(),
            Ty::String => "ArcStr".into(),
            Ty::Text => {
                self.use_pkg("Tpl");
                "Tpl::Text".into()
            }
            Ty::SourceInfo => "SourceInfo".into(),
            Ty::Unit => "()".into(),
            Ty::FuncPtr => self.err("function values are not supported in templates".into()),
            Ty::Ref(t) => format!("metamodelica::Ref<{}>", self.rust_ty(t)),
            Ty::List(t) => format!("metamodelica::List<{}>", self.rust_ty(t)),
            Ty::Option(t) => format!("Option<{}>", self.rust_ty(t)),
            Ty::Array(t) => format!("metamodelica::Array<{}>", self.rust_ty(t)),
            Ty::Tuple(ts) => format!(
                "({})",
                ts.iter().map(|t| self.rust_ty(t)).collect::<Vec<_>>().join(", ")
            ),
            Ty::Named(n) => self.type_path(n),
            Ty::Generic(n, ts) => {
                let args = ts.iter().map(|t| self.rust_ty(t)).collect::<Vec<_>>().join(", ");
                format!("{}<{args}>", self.type_path(n))
            }
            Ty::TyVar(n) => self.err(format!("type variable {n} in a template signature")),
        }
    }

    fn out_ty(&mut self, outs: &[Ty]) -> String {
        match outs {
            [] => "()".into(),
            [t] => self.rust_ty(t),
            ts => format!(
                "({})",
                ts.iter().map(|t| self.rust_ty(t)).collect::<Vec<_>>().join(", ")
            ),
        }
    }

    fn token(&mut self, t: &Tpl::StringToken) -> String {
        self.use_pkg("Tpl");
        let inner = match t {
            Tpl::StringToken::ST_NEW_LINE => "Tpl::StringToken::ST_NEW_LINE".to_string(),
            Tpl::StringToken::ST_STRING { value } => format!(
                "Tpl::StringToken::ST_STRING {{ value: literal!({}) }}",
                rust_string(value)
            ),
            Tpl::StringToken::ST_LINE { line } => {
                format!("Tpl::StringToken::ST_LINE {{ line: literal!({}) }}", rust_string(line))
            }
            Tpl::StringToken::ST_STRING_LIST {
                strList,
                lastHasNewLine,
            } => {
                let items: Vec<String> = strList
                    .iter()
                    .map(|s| format!("literal!({})", rust_string(s)))
                    .collect();
                format!(
                    "Tpl::StringToken::ST_STRING_LIST {{ strList: metamodelica::list![{}], lastHasNewLine: {lastHasNewLine} }}",
                    items.join(", ")
                )
            }
            Tpl::StringToken::ST_BLOCK { .. } => return self.err("block tokens are not constants".into()),
        };
        format!("metamodelica::Ref::new({inner})")
    }

    fn literal(&mut self, v: &str, want: Option<&Ty>) -> String {
        if v == "NONE()" {
            return "None".into();
        }
        let is_real = v.parse::<i64>().is_err() && v.parse::<f64>().is_ok();
        let real = || {
            if is_real {
                format!("{v}_f64")
            } else {
                format!("{v}.0_f64")
            }
        };
        match want.map(Ty::strip_ref) {
            Some(Ty::Real) => format!("metamodelica::OrderedFloat({})", real()),
            Some(Ty::F64) => real(),
            _ if is_real => format!("metamodelica::OrderedFloat({})", real()),
            _ => v.to_string(),
        }
    }

    fn susan_sig(&mut self, rust: String, ins: &Typed, outs: &Typed, modes: impl Fn(&str, &Ty) -> Mode) -> Sig {
        let params = ins
            .iter()
            .map(|(n, t)| {
                let ty = self.susan_ty(t);
                Param {
                    mode: modes(n, &ty),
                    ty,
                }
            })
            .collect();
        let outs = outs.iter().map(|(_, t)| self.susan_ty(t)).collect();
        Sig {
            rust,
            params,
            outs,
            fallible: true,
        }
    }

    fn index_sig(&self, pkg: &str, name: &str) -> Option<Sig> {
        let f = self.idx.packages.get(pkg)?.functions.get(name)?;
        Some(Sig {
            rust: f.rust.clone(),
            params: f
                .params
                .iter()
                .map(|a| Param {
                    mode: if a.borrowed {
                        Mode::Borrowed
                    } else if is_copy(&a.ty) {
                        Mode::Copy
                    } else {
                        Mode::Owned
                    },
                    ty: a.ty.clone(),
                })
                .collect(),
            outs: f.outs.clone(),
            fallible: f.fallible,
        })
    }

    /// The union of `pkg` holding record `rec`, preferring `hint`.
    fn record(
        &self,
        pkg: &str,
        rec: &str,
        hint: Option<&str>,
    ) -> Option<(String, &'a str, bool, &'a openmodelica_susan_index::Record)> {
        let p = self.idx.packages.get(pkg)?;
        let find = |tn: &str| match p.types.get(tn) {
            Some(TypeDef::Union {
                rust,
                is_struct,
                records,
            }) => records
                .iter()
                .find(|r| r.name == rec)
                .map(|r| (rust.as_str(), *is_struct, r)),
            _ => None,
        };
        if let Some(h) = hint.and_then(|h| h.strip_prefix(&format!("{pkg}."))) {
            if let Some((rust, s, r)) = find(h) {
                return Some((format!("{pkg}.{h}"), rust, s, r));
            }
        }
        for (tn, t) in &p.types {
            if let TypeDef::Union {
                rust,
                is_struct,
                records,
            } = t
            {
                if let Some(r) = records.iter().find(|r| r.name == rec) {
                    return Some((format!("{pkg}.{tn}"), rust.as_str(), *is_struct, r));
                }
            }
        }
        None
    }

    fn pattern(&mut self, m: &MatchingExp, ty: &Ty, binds: &mut Vec<(String, Ty)>) -> String {
        match m {
            MatchingExp::REST_MATCH => return "_".into(),
            MatchingExp::BIND_MATCH { bindIdent } => {
                binds.push((bindIdent.to_string(), ty.clone()));
                return bindIdent.to_string();
            }
            MatchingExp::BIND_AS_MATCH { bindIdent, matchingExp } => {
                binds.push((bindIdent.to_string(), ty.clone()));
                let inner = self.pattern(matchingExp, ty, binds);
                return format!("{bindIdent} @ {inner}");
            }
            _ => {}
        }
        match ty {
            Ty::Ref(t) => return format!("Deref @ {}", self.pattern(m, t, binds)),
            Ty::Named(n) => {
                if let Some(TypeDef::Alias(t)) = self.named(n) {
                    let t = t.clone();
                    return self.pattern(m, &t, binds);
                }
            }
            _ => {}
        }
        match m {
            MatchingExp::RECORD_MATCH { fieldMatchings, .. } if *ty == Ty::SourceInfo => {
                let mut fields = vec![];
                for (fname, fm) in fieldMatchings {
                    let Some((f, fty)) = SOURCE_INFO_FIELDS.iter().find(|(f, _)| *f == fname.as_str()) else {
                        fields.push(self.err(format!("SOURCEINFO has no field {fname}")));
                        continue;
                    };
                    let pat = self.pattern(fm, fty, binds);
                    if pat != "_" {
                        fields.push(format!("{f}: {pat}"));
                    }
                }
                fields.push("..".into());
                format!("SourceInfo {{ {} }}", fields.join(", "))
            }
            MatchingExp::RECORD_MATCH {
                tagName,
                fieldMatchings,
            } => {
                let (pkg, rec) = split_path(tagName);
                let hint = match ty {
                    Ty::Named(n) => Some(n.as_str()),
                    _ => None,
                };
                let Some(pkg) = pkg.or_else(|| hint.and_then(|h| h.rsplit_once('.')).map(|(p, _)| p.to_string()))
                else {
                    return self.err(format!("record {rec} without a package"));
                };
                let Some((_, rust, is_struct, r)) = self.record(&pkg, &rec, hint) else {
                    return self.err(format!("unknown record {pkg}.{rec}"));
                };
                let p = self.use_pkg(&pkg);
                let path = if is_struct {
                    format!("{p}::{rust}")
                } else {
                    format!("{p}::{rust}::{rec}")
                };
                let mut fields = vec![];
                for (fname, fm) in fieldMatchings {
                    let Some(f) = r.fields.iter().find(|f| f.name == fname.as_str()) else {
                        fields.push(self.err(format!("record {pkg}.{rec} has no field {fname}")));
                        continue;
                    };
                    let pat = self.pattern(fm, &f.ty, binds);
                    if pat != "_" {
                        fields.push(format!("{}: {pat}", f.rust));
                    }
                }
                fields.push("..".into());
                format!("{path} {{ {} }}", fields.join(", "))
            }
            MatchingExp::SOME_MATCH { value } => match ty {
                Ty::Option(t) => format!("Some({})", self.pattern(value, t, binds)),
                _ => self.err(format!("SOME pattern against {ty:?}")),
            },
            MatchingExp::NONE_MATCH => "None".into(),
            MatchingExp::TUPLE_MATCH { tupleArgs } => match ty {
                Ty::Tuple(ts) if ts.len() == tupleArgs.len() as usize => {
                    let ps: Vec<String> = tupleArgs
                        .iter()
                        .zip(ts)
                        .map(|(a, t)| self.pattern(a, t, binds))
                        .collect();
                    format!("({})", ps.join(", "))
                }
                _ => self.err(format!("tuple pattern against {ty:?}")),
            },
            MatchingExp::LIST_MATCH { listElts } => match ty {
                Ty::List(e) => {
                    let elts: Vec<Ref<MatchingExp>> = listElts.iter().cloned().collect();
                    let mut out = "Deref @ metamodelica::ListNode::Nil".to_string();
                    for el in elts.iter().rev() {
                        let h = self.pattern(el, e, binds);
                        out = format!("Deref @ metamodelica::ListNode::Cons {{ head: {h}, tail: {out} }}");
                    }
                    out
                }
                _ => self.err(format!("list pattern against {ty:?}")),
            },
            MatchingExp::LIST_CONS_MATCH { head, rest } => match ty {
                Ty::List(e) => {
                    let h = self.pattern(head, e, binds);
                    let t = self.pattern(rest, ty, binds);
                    format!("Deref @ metamodelica::ListNode::Cons {{ head: {h}, tail: {t} }}")
                }
                _ => self.err(format!("cons pattern against {ty:?}")),
            },
            MatchingExp::STRING_MATCH { value } => format!("Deref @ {}", rust_string(value)),
            MatchingExp::LITERAL_MATCH { value, .. } => match ty {
                Ty::Real | Ty::F64 => self.err(format!("Real literal pattern {value}")),
                _ => value.to_string(),
            },
            _ => unreachable!(),
        }
    }

    fn call_sig(&mut self, name: &PathIdent) -> Result<(String, Sig), String> {
        let (pkg, n) = split_path(name);
        match pkg {
            None => {
                if let Some(s) = self.local_funs.get(&n) {
                    return Ok((ident(&s.rust), s.clone()));
                }
                if let Some(s) = self.index_sig("builtin", &n) {
                    return Ok((s.rust.clone(), s));
                }
                Err(format!("unknown function {n}"))
            }
            Some(p) if p == self.pkg => match self.local_funs.get(&n) {
                Some(s) => Ok((ident(&s.rust), s.clone())),
                None => Err(format!("unknown function {p}.{n}")),
            },
            Some(p) => {
                if let Some(s) = self.tpl_funs.get(&(p.clone(), n.clone())).cloned() {
                    let pp = self.use_pkg(&p);
                    return Ok((format!("{pp}::{}", ident(&s.rust)), s));
                }
                if let Some(s) = self.index_sig(&p, &n) {
                    let pp = self.use_pkg(&p);
                    return Ok((format!("{pp}::{}", s.rust), s));
                }
                Err(format!("unknown function {p}.{n}"))
            }
        }
    }

    fn arg(&mut self, e: &MMExp, p: &Param, env: &Env, moves: &mut HashMap<String, usize>) -> String {
        if let MMExp::MM_IDENT { ident: id } = e {
            if let PathIdent::IDENT { ident: n } = &**id {
                if let Some(v) = env.get(n.as_str()) {
                    let n = n.to_string();
                    return match (p.mode, v.kind) {
                        (Mode::Borrowed, Kind::Owned) => format!("&{n}"),
                        (Mode::Borrowed, Kind::Ref) => n,
                        (Mode::Copy, Kind::Owned) => n,
                        (Mode::Copy, Kind::Ref) => format!("*{n}"),
                        (Mode::Owned, Kind::Ref) => format!("{n}.clone()"),
                        (Mode::Owned, Kind::Owned) => {
                            let can_move = match moves.get_mut(&n) {
                                Some(c) => {
                                    *c -= 1;
                                    *c == 0
                                }
                                None => false,
                            };
                            if can_move { n } else { format!("{n}.clone()") }
                        }
                    };
                }
            }
        }
        let v = self.value(e, Some(&p.ty), env, moves);
        match p.mode {
            Mode::Borrowed => format!("&{v}"),
            _ => v,
        }
    }

    fn value(&mut self, e: &MMExp, want: Option<&Ty>, env: &Env, moves: &mut HashMap<String, usize>) -> String {
        match e {
            MMExp::MM_STRING { value } => format!("literal!({})", rust_string(value)),
            MMExp::MM_LITERAL { value } => self.literal(value, want),
            MMExp::MM_STR_TOKEN { value } => self.token(value),
            MMExp::MM_IDENT { ident: id } => {
                let (pkg, n) = split_path(id);
                if pkg.is_none() {
                    if let Some(v) = env.get(&n) {
                        let p = Param {
                            ty: v.ty.clone(),
                            mode: if is_copy(&v.ty) { Mode::Copy } else { Mode::Owned },
                        };
                        return self.arg(e, &p, env, moves);
                    }
                    if self.local_consts.contains_key(&n) {
                        return format!("{}()?", ident(&n));
                    }
                    if n == "NONE" {
                        return "None".into();
                    }
                    return self.err(format!("unknown identifier {n}"));
                }
                let p = pkg.unwrap();
                if p == self.pkg && self.local_consts.contains_key(&n) {
                    return format!("{}()?", ident(&n));
                }
                if self.tpl_consts.contains_key(&(p.clone(), n.clone())) {
                    let pp = self.use_pkg(&p);
                    return format!("{pp}::{}()?", ident(&n));
                }
                if let Some(c) = self.idx.packages.get(&p).and_then(|pk| pk.constants.get(&n)).cloned() {
                    let pp = self.use_pkg(&p);
                    return match c.access {
                        ConstAccess::Call => format!("{pp}::{}()", c.rust),
                        ConstAccess::Value => format!("{pp}::{}.clone()", c.rust),
                        ConstAccess::Deref => format!("(*{pp}::{}).clone()", c.rust),
                        ConstAccess::Str => format!("ArcStr::from({pp}::{})", c.rust),
                    };
                }
                self.err(format!("unknown constant {p}.{n}"))
            }
            MMExp::MM_FN_CALL { fnName, args } => self.call(fnName, args, want, env, moves),
            _ => self.err("unexpected statement in an expression".into()),
        }
    }

    fn call(
        &mut self,
        name: &PathIdent,
        args: &List<Ref<MMExp>>,
        want: Option<&Ty>,
        env: &Env,
        moves: &mut HashMap<String, usize>,
    ) -> String {
        let args: Vec<Ref<MMExp>> = args.iter().cloned().collect();
        let (pkg, n) = split_path(name);
        if pkg.is_none() {
            match n.as_str() {
                "SOME" if args.len() == 1 => {
                    let inner = match want {
                        Some(Ty::Option(t)) => Some((**t).clone()),
                        _ => None,
                    };
                    let p = Param {
                        mode: Mode::Owned,
                        ty: inner.unwrap_or(Ty::Unit),
                    };
                    return format!("Some({})", self.arg(&args[0], &p, env, moves));
                }
                "NONE" if args.is_empty() => return "None".into(),
                _ => {}
            }
        }
        if let Some(p) = &pkg {
            if let Some((union, rust, is_struct, r)) = self.record(p, &n, None) {
                if r.fields.len() != args.len() {
                    return self.err(format!("{p}.{n} takes {} fields, got {}", r.fields.len(), args.len()));
                }
                let fields: Vec<(String, Ty)> = r.fields.iter().map(|f| (f.rust.clone(), f.ty.clone())).collect();
                let pp = self.use_pkg(p);
                let path = if is_struct {
                    format!("{pp}::{rust}")
                } else {
                    format!("{pp}::{rust}::{n}")
                };
                let vals: Vec<String> = fields
                    .iter()
                    .zip(&args)
                    .map(|((f, t), a)| {
                        let param = Param {
                            mode: if is_copy(t) { Mode::Copy } else { Mode::Owned },
                            ty: t.clone(),
                        };
                        format!("{f}: {}", self.arg(a, &param, env, moves))
                    })
                    .collect();
                let v = format!("{path} {{ {} }}", vals.join(", "));
                return if self.idx.is_boxed(&union) {
                    format!("metamodelica::Ref::new({v})")
                } else {
                    v
                };
            }
        }
        let (callee, sig) = match self.call_sig(name) {
            Ok(x) => x,
            Err(e) => return self.err(e),
        };
        if sig.params.len() != args.len() {
            return self.err(format!(
                "{} takes {} arguments, got {}",
                path_string(name),
                sig.params.len(),
                args.len()
            ));
        }
        let vals: Vec<String> = sig
            .params
            .iter()
            .zip(&args)
            .map(|(p, a)| self.arg(a, p, env, moves))
            .collect();
        format!("{callee}({}){}", vals.join(", "), if sig.fallible { "?" } else { "" })
    }

    fn uses_in(e: &MMExp, out: &mut Vec<String>) {
        match e {
            MMExp::MM_ASSIGN { rhs, .. } => Self::uses_in(rhs, out),
            MMExp::MM_FN_CALL { args, .. } => args.iter().for_each(|a| Self::uses_in(a, out)),
            MMExp::MM_IDENT { ident: id } => {
                if let PathIdent::IDENT { ident: n } = &**id {
                    out.push(n.to_string());
                }
            }
            _ => {}
        }
    }

    fn lhs(e: &MMExp) -> Vec<String> {
        match e {
            MMExp::MM_ASSIGN { lhsArgs, .. } => lhsArgs.iter().map(|s| s.to_string()).filter(|s| s != "_").collect(),
            _ => vec![],
        }
    }

    /// Prints `stmts`; `results` are read after the last statement.
    fn block(&mut self, stmts: &[Ref<MMExp>], env: &mut Env, results: &[String], indent: &str, out: &mut String) {
        let mut later: Vec<HashSet<String>> = vec![HashSet::new(); stmts.len() + 1];
        later[stmts.len()] = results.iter().cloned().collect();
        for i in (0..stmts.len()).rev() {
            let mut u = vec![];
            Self::uses_in(&stmts[i], &mut u);
            let mut s = later[i + 1].clone();
            for l in Self::lhs(&stmts[i]) {
                s.remove(&l);
            }
            s.extend(u);
            later[i] = s;
        }
        for (i, st) in stmts.iter().enumerate() {
            let (lhs, rhs): (Vec<String>, &MMExp) = match &**st {
                MMExp::MM_ASSIGN { lhsArgs, rhs } => (lhsArgs.iter().map(|s| s.to_string()).collect(), &**rhs),
                e @ MMExp::MM_FN_CALL { .. } => (vec![], e),
                e => {
                    let e = self.err(format!("unexpected statement {e:?}"));
                    writeln!(out, "{indent}{e};").unwrap();
                    continue;
                }
            };
            let mut u = vec![];
            Self::uses_in(rhs, &mut u);
            let mut moves: HashMap<String, usize> = HashMap::new();
            for v in &u {
                *moves.entry(v.clone()).or_default() += 1;
            }
            moves.retain(|v, _| {
                env.get(v).is_some_and(|x| x.kind == Kind::Owned)
                    && (lhs.contains(v) || (!later[i + 1].contains(v) && !env[v].outer))
            });
            let want = match lhs.as_slice() {
                [l] => env.get(l).map(|v| v.ty.clone()),
                _ => None,
            };
            let rhs_s = self.value(rhs, want.as_ref(), env, &mut moves);
            match lhs.as_slice() {
                [] => writeln!(out, "{indent}{rhs_s};").unwrap(),
                [l] => writeln!(out, "{indent}{l} = {rhs_s};").unwrap(),
                ls => writeln!(out, "{indent}({}) = {rhs_s};", ls.join(", ")).unwrap(),
            }
        }
    }

    fn assigned(stmts: &[Ref<MMExp>]) -> Vec<String> {
        let mut seen = vec![];
        for s in stmts {
            for l in Self::lhs(s) {
                if !seen.contains(&l) {
                    seen.push(l);
                }
            }
        }
        seen
    }

    fn result(&mut self, names: &[String], env: &Env) -> String {
        let vals: Vec<String> = names
            .iter()
            .map(|n| match env.get(n) {
                Some(Var { kind: Kind::Owned, .. }) => n.clone(),
                Some(Var {
                    kind: Kind::Ref, ty, ..
                }) if is_copy(ty) => format!("*{n}"),
                Some(_) => format!("{n}.clone()"),
                None => self.err(format!("unknown result {n}")),
            })
            .collect();
        match vals.as_slice() {
            [v] => format!("Ok({v})"),
            vs => format!("Ok(({}))", vs.join(", ")),
        }
    }

    /// One match arm (or loop case): `binds` come from the patterns. With
    /// `tail`, the last statement is a self call that becomes a jump.
    #[allow(clippy::too_many_arguments)]
    fn arm(
        &mut self,
        stmts: &[Ref<MMExp>],
        binds: &[(String, Ty, Kind)],
        locals: &HashMap<String, Ty>,
        env: &Env,
        results: Option<&[String]>,
        tail: Option<&[(String, Param)]>,
        indent: &str,
        out: &mut String,
    ) {
        let mut env = env.clone();
        for (n, t, k) in binds {
            env.insert(
                n.clone(),
                Var {
                    ty: t.clone(),
                    kind: *k,
                    outer: false,
                },
            );
        }
        let (stmts, last) = match tail {
            Some(_) => (&stmts[..stmts.len() - 1], stmts.last()),
            None => (stmts, None),
        };
        for n in Self::assigned(stmts) {
            match env.get(&n) {
                Some(Var {
                    kind: Kind::Ref,
                    ty,
                    outer: false,
                }) => {
                    let ty = ty.clone();
                    writeln!(
                        out,
                        "{indent}let mut {n} = {};",
                        if is_copy(&ty) {
                            format!("*{n}")
                        } else {
                            format!("{n}.clone()")
                        }
                    )
                    .unwrap();
                    env.insert(
                        n,
                        Var {
                            ty,
                            kind: Kind::Owned,
                            outer: false,
                        },
                    );
                }
                Some(_) => {}
                None => {
                    let ty = locals.get(&n).cloned().unwrap_or(Ty::Unit);
                    writeln!(out, "{indent}let mut {n};").unwrap();
                    env.insert(
                        n,
                        Var {
                            ty,
                            kind: Kind::Owned,
                            outer: false,
                        },
                    );
                }
            }
        }
        let mut after: Vec<String> = results.unwrap_or(&[]).to_vec();
        if let Some(l) = last {
            Self::uses_in(l, &mut after);
        }
        self.block(stmts, &mut env, &after, indent, out);
        if let (Some(params), Some(l)) = (tail, last) {
            let MMExp::MM_ASSIGN { rhs, .. } = &**l else {
                unreachable!()
            };
            let MMExp::MM_FN_CALL { args, .. } = &**rhs else {
                unreachable!()
            };
            let mut moves: HashMap<String, usize> = HashMap::new();
            let mut u = vec![];
            Self::uses_in(rhs, &mut u);
            for v in u {
                if env.get(&v).is_some_and(|x| x.kind == Kind::Owned && !x.outer) {
                    *moves.entry(v).or_default() += 1;
                }
            }
            let vals: Vec<String> = params
                .iter()
                .zip(args)
                .map(|((_, p), a)| self.arg(a, p, &env, &mut moves))
                .collect();
            let names: Vec<&str> = params.iter().map(|(n, _)| n.as_str()).collect();
            writeln!(out, "{indent}({}) = ({});", names.join(", "), vals.join(", ")).unwrap();
            writeln!(out, "{indent}continue '__tco;").unwrap();
        } else if let Some(r) = results {
            let r = self.result(r, &env);
            writeln!(out, "{indent}{r}").unwrap();
        }
    }

    /// Whether the arm ends in `outs := name(args)` whose borrowed arguments
    /// are references into the inputs, so the call can become a jump.
    fn is_tail_call(
        name: &str,
        pkg: &str,
        stmts: &[Ref<MMExp>],
        outs: &[String],
        params: &[(String, Param)],
        binds: &[(String, Ty, Kind)],
    ) -> bool {
        let Some(MMExp::MM_ASSIGN { lhsArgs, rhs }) = stmts.last().map(|s| &**s) else {
            return false;
        };
        if lhsArgs.iter().map(|s| s.to_string()).collect::<Vec<_>>() != outs {
            return false;
        }
        let MMExp::MM_FN_CALL { fnName, args } = &**rhs else {
            return false;
        };
        let (p, n) = split_path(fnName);
        if n != name || p.is_some_and(|p| p != pkg) || args.len() as usize != params.len() {
            return false;
        }
        let assigned = Self::assigned(&stmts[..stmts.len() - 1]);
        params.iter().zip(args).all(|((_, p), a)| {
            if p.mode != Mode::Borrowed {
                return true;
            }
            let MMExp::MM_IDENT { ident: id } = &**a else {
                return false;
            };
            let PathIdent::IDENT { ident: v } = &**id else {
                return false;
            };
            let v = v.as_str();
            !assigned.iter().any(|x| x == v)
                && (binds.iter().any(|(b, _, k)| b == v && *k == Kind::Ref)
                    || params.iter().any(|(n, q)| n == v && q.mode == Mode::Borrowed))
        })
    }

    fn locals_map(&mut self, locals: &Typed) -> HashMap<String, Ty> {
        locals.iter().map(|(n, t)| (n.to_string(), self.susan_ty(t))).collect()
    }

    fn function(
        &mut self,
        is_public: bool,
        name: &str,
        ins: &Typed,
        outs: &Typed,
        locals: &Typed,
        stmts: &List<Ref<MMExp>>,
        dest: &mut String,
    ) {
        self.current = name.to_string();
        let mut body = String::new();
        let out = &mut body;
        let mut has_tail = false;
        let sig = self.local_funs[name].clone();
        let stmts: Vec<Ref<MMExp>> = stmts.iter().cloned().collect();
        let in_names: Vec<String> = ins.iter().map(|(n, _)| n.to_string()).collect();
        let out_names: Vec<String> = outs.iter().map(|(n, _)| n.to_string()).collect();
        let kind = match stmts.as_slice() {
            [s] if matches!(&**s, MMExp::MM_MATCH { .. }) => Body::Match,
            [s] if matches!(&**s, MMExp::MM_LIST_FOR_LOOP { .. }) => Body::ListLoop,
            [s] if matches!(&**s, MMExp::MM_FOR_LOOP { .. }) => Body::ArrayLoop,
            _ => Body::Statements,
        };
        let prefix = if kind == Body::Match { "in_" } else { "" };
        let mut params = vec![];
        let mut env = Env::new();
        for (n, p) in in_names.iter().zip(&sig.params) {
            let ty = self.rust_ty(&p.ty);
            let pn = format!("{prefix}{n}");
            params.push((pn.clone(), p.mode, ty));
            env.insert(
                pn,
                Var {
                    ty: p.ty.clone(),
                    kind: if p.mode == Mode::Borrowed {
                        Kind::Ref
                    } else {
                        Kind::Owned
                    },
                    outer: false,
                },
            );
        }
        let ret = self.out_ty(&sig.outs);
        let locals = self.locals_map(locals);
        match kind {
            Body::Statements => {
                let outs: Vec<String> = out_names.iter().map(|n| format!("out_{n}")).collect();
                let assigned = Self::assigned(&stmts);
                for o in &outs {
                    if !assigned.contains(o) {
                        self.err(format!("{o} is never assigned"));
                    }
                }
                self.arm(&stmts, &[], &locals, &env, Some(&outs), None, "    ", out);
            }
            Body::Match => {
                let MMExp::MM_MATCH { matchCases } = &*stmts[0] else {
                    unreachable!()
                };
                let cases: Vec<(Vec<Ref<MatchingExp>>, Vec<Ref<MMExp>>)> = matchCases
                    .iter()
                    .map(|(ps, b)| (ps.iter().cloned().collect(), b.iter().cloned().collect()))
                    .collect();
                let cols: Vec<(String, Param)> = in_names
                    .iter()
                    .map(|n| format!("in_{n}"))
                    .zip(sig.params.iter().cloned())
                    .collect();
                // Text columns only ever bind, so they are moved into each arm
                // rather than borrowed by the match.
                let moved: Vec<bool> = cols
                    .iter()
                    .enumerate()
                    .map(|(i, (_, p))| {
                        p.ty == Ty::Text
                            && cases.iter().all(|(ps, _)| {
                                matches!(
                                    ps.get(i).map(|m| &**m),
                                    Some(MatchingExp::BIND_MATCH { .. } | MatchingExp::REST_MATCH)
                                )
                            })
                    })
                    .collect();
                let scrut: Vec<String> = cols
                    .iter()
                    .zip(&moved)
                    .filter(|(_, m)| !**m)
                    .map(|((n, p), _)| {
                        if p.mode == Mode::Owned {
                            format!("&{n}")
                        } else {
                            n.clone()
                        }
                    })
                    .collect();
                let scrut = if scrut.len() == 1 {
                    scrut[0].clone()
                } else {
                    format!("({})", scrut.join(", "))
                };
                let mut arms = vec![];
                let mut any_tail = false;
                for (pats, body) in &cases {
                    let mut binds: Vec<(String, Ty, Kind)> = vec![];
                    let mut ps = vec![];
                    let mut takes = vec![];
                    for (i, (m, (cn, p))) in pats.iter().zip(&cols).enumerate() {
                        if moved[i] {
                            if let MatchingExp::BIND_MATCH { bindIdent } = &**m {
                                takes.push(format!("let mut {bindIdent} = {cn};"));
                                binds.push((bindIdent.to_string(), Ty::Text, Kind::Owned));
                            }
                            continue;
                        }
                        let mut bs = vec![];
                        ps.push(self.pattern(m, &p.ty, &mut bs));
                        let kind = if p.mode == Mode::Copy { Kind::Owned } else { Kind::Ref };
                        binds.extend(bs.into_iter().map(|(n, t)| (n, t, kind)));
                    }
                    let pat = if ps.len() == 1 {
                        ps[0].clone()
                    } else {
                        format!("({})", ps.join(", "))
                    };
                    let tail = Self::is_tail_call(name, &self.pkg, body, &out_names, &cols, &binds);
                    any_tail |= tail;
                    arms.push((pat, takes, binds, body, tail));
                }
                let indent = if any_tail { "    " } else { "" };
                if any_tail {
                    writeln!(out, "    '__tco: loop {{").unwrap();
                    writeln!(out, "    break ::match_deref::match_deref! {{ match {scrut} {{").unwrap();
                } else {
                    writeln!(out, "    ::match_deref::match_deref! {{ match {scrut} {{").unwrap();
                }
                for (pat, takes, binds, body, tail) in arms {
                    writeln!(out, "{indent}        {pat} => {{").unwrap();
                    for t in takes {
                        writeln!(out, "{indent}            {t}").unwrap();
                    }
                    let inner = format!("{indent}            ");
                    self.arm(
                        body,
                        &binds,
                        &locals,
                        &env,
                        Some(&out_names),
                        if tail { Some(&cols) } else { None },
                        &inner,
                        out,
                    );
                    writeln!(out, "{indent}        }}").unwrap();
                }
                writeln!(out, "{indent}        _ => Err(\"{}: no case matched\"),", name).unwrap();
                if any_tail {
                    writeln!(out, "        }} }};\n    }}").unwrap();
                } else {
                    writeln!(out, "    }} }}").unwrap();
                }
                has_tail = any_tail;
            }
            Body::ListLoop => {
                let MMExp::MM_LIST_FOR_LOOP {
                    eltName,
                    listName,
                    matchLocals,
                    matchCases,
                } = &*stmts[0]
                else {
                    unreachable!()
                };
                let Some(list) = env.get(listName.as_str()).cloned() else {
                    self.err(format!("unknown list {listName}"));
                    return;
                };
                let Ty::List(elt_ty) = list.ty else {
                    self.err(format!("{listName} is not a list"));
                    return;
                };
                let mut loop_env = env.clone();
                for v in loop_env.values_mut() {
                    v.outer = true;
                }
                let iter = if list.kind == Kind::Ref {
                    listName.to_string()
                } else {
                    format!("&{listName}")
                };
                let mut locals = locals;
                locals.extend(self.locals_map(matchLocals));
                writeln!(out, "    for {eltName} in {iter} {{").unwrap();
                writeln!(out, "        ::match_deref::match_deref! {{ match {eltName} {{").unwrap();
                let mut has_default = false;
                for (pats, body) in matchCases {
                    let mut binds = vec![];
                    let ps: Vec<String> = pats.iter().map(|m| self.pattern(m, &elt_ty, &mut binds)).collect();
                    let binds: Vec<(String, Ty, Kind)> = binds.into_iter().map(|(n, t)| (n, t, Kind::Ref)).collect();
                    if ps.iter().all(|p| p == "_") && binds.is_empty() {
                        has_default = true;
                    }
                    writeln!(out, "            {} => {{", ps.join(", ")).unwrap();
                    let body: Vec<Ref<MMExp>> = body.iter().cloned().collect();
                    let mut sub = String::new();
                    self.arm(
                        &body,
                        &binds,
                        &locals,
                        &loop_env,
                        None,
                        None,
                        "                ",
                        &mut sub,
                    );
                    out.push_str(&sub);
                    writeln!(out, "            }}").unwrap();
                }
                if !has_default {
                    writeln!(out, "            _ => return Err(\"{}: no case matched\"),", name).unwrap();
                }
                writeln!(out, "        }} }}").unwrap();
                writeln!(out, "    }}").unwrap();
                let r = self.result(&out_names, &env);
                writeln!(out, "    {r}").unwrap();
            }
            Body::ArrayLoop => {
                self.err("array loops are not supported".into());
            }
        }
        writeln!(out, "}}\n").unwrap();
        let params: Vec<String> = params
            .iter()
            .map(|(pn, mode, ty)| match mode {
                Mode::Borrowed if has_tail => format!("mut {pn}: &'a {ty}"),
                Mode::Borrowed => format!("{pn}: &{ty}"),
                _ => format!("mut {pn}: {ty}"),
            })
            .collect();
        let generics = if has_tail { "<'a>" } else { "" };
        writeln!(
            dest,
            "{}fn {}{generics}({}) -> Result<{ret}> {{",
            if is_public { "pub " } else { "" },
            ident(&sig.rust),
            params.join(", ")
        )
        .unwrap();
        dest.push_str(&body);
    }
}

fn template_crate(dir: &std::path::Path, pkg: &str) -> Option<String> {
    let src = std::fs::read_to_string(dir.join(format!("{pkg}.tpl"))).ok()?;
    Some(interface_crate(&annotation_interface(&src)?))
}

/// Prints `mm` as the Rust module of its package; returns its crate and code.
/// `tpl_dir` holds the `.tpl` files of the imported template packages.
pub fn print(
    tpl: &TemplPackage,
    mm: &MMPackage,
    idx: &Index,
    tpl_dir: &std::path::Path,
) -> Result<(String, String), Vec<String>> {
    let pkg = path_string(&mm.name);
    let Some(krate) = annotation_interface(&mm.annotationFooter).map(|i| interface_crate(&i)) else {
        return Err(vec![format!("{pkg}: no __OpenModelica_Interface annotation")]);
    };
    let mut p = Printer {
        idx,
        pkg: pkg.clone(),
        krate,
        tpl_crates: HashMap::new(),
        uses: BTreeSet::new(),
        local_funs: HashMap::new(),
        local_consts: HashMap::new(),
        tpl_funs: HashMap::new(),
        tpl_consts: HashMap::new(),
        errors: vec![],
        current: String::new(),
    };
    for ASTDef {
        importPackage, types, ..
    } in &tpl.astDefs
    {
        let ip = path_string(importPackage);
        let Some(c) = template_crate(tpl_dir, &ip) else {
            continue;
        };
        p.tpl_crates.insert(ip.clone(), c);
        for (n, ti) in types {
            match ti {
                TypeInfo::TI_FUN_TYPE { inArgs, outArgs, .. } => {
                    let s = p.susan_sig(n.to_string(), inArgs, outArgs, |_, t| convention(t));
                    p.tpl_funs.insert((ip.clone(), n.to_string()), s);
                }
                TypeInfo::TI_CONST_TYPE { constType } => {
                    let t = p.susan_ty(constType);
                    p.tpl_consts.insert((ip.clone(), n.to_string()), t);
                }
                _ => {}
            }
        }
    }
    for d in &mm.mmDeclarations {
        match d {
            MMDeclaration::MM_FUN {
                name,
                inArgs,
                outArgs,
                statements,
                ..
            } => {
                let list_loop = matches!(
                    statements.iter().next().map(|s| &**s),
                    Some(MMExp::MM_LIST_FOR_LOOP { .. })
                );
                let out_names: HashSet<String> = outArgs.iter().map(|(n, _)| n.to_string()).collect();
                let s = p.susan_sig(name.to_string(), inArgs, outArgs, |n, t| {
                    if list_loop && out_names.contains(n) {
                        Mode::Owned
                    } else {
                        convention(t)
                    }
                });
                p.local_funs.insert(name.to_string(), s);
            }
            MMDeclaration::MM_STR_TOKEN_DECL { name, .. } => {
                p.local_consts
                    .insert(name.to_string(), Ty::Ref(Box::new(Ty::Named("Tpl.StringToken".into()))));
            }
            MMDeclaration::MM_LITERAL_DECL { name, litType, .. } => {
                let t = p.susan_ty(litType);
                p.local_consts.insert(name.to_string(), t);
            }
            MMDeclaration::MM_IMPORT { .. } => {}
        }
    }

    let mut body = String::new();
    for d in &mm.mmDeclarations {
        match d {
            MMDeclaration::MM_FUN {
                isPublic,
                name,
                inArgs,
                outArgs,
                locals,
                statements,
                ..
            } => {
                p.function(*isPublic, name, inArgs, outArgs, locals, statements, &mut body);
            }
            MMDeclaration::MM_STR_TOKEN_DECL { isPublic, name, value } => {
                let v = p.token(value);
                writeln!(
                    body,
                    "{}fn {}() -> Result<metamodelica::Ref<Tpl::StringToken>> {{\n    Ok({v})\n}}\n",
                    if *isPublic { "pub " } else { "" },
                    ident(name)
                )
                .unwrap();
            }
            MMDeclaration::MM_LITERAL_DECL {
                isPublic,
                name,
                value,
                litType,
            } => {
                let t = p.susan_ty(litType);
                let ty = p.rust_ty(&t);
                let v = p.literal(value, Some(&t));
                writeln!(
                    body,
                    "{}fn {}() -> Result<{ty}> {{\n    Ok({v})\n}}\n",
                    if *isPublic { "pub " } else { "" },
                    ident(name)
                )
                .unwrap();
            }
            MMDeclaration::MM_IMPORT { .. } => {}
        }
    }
    if !p.errors.is_empty() {
        let mut errs = p.errors.clone();
        errs.sort();
        errs.dedup();
        return Err(errs);
    }

    let mut out = String::new();
    writeln!(out, "// Generated by Susan from {pkg}.tpl.").unwrap();
    writeln!(out, "#![allow(warnings)]\n").unwrap();
    writeln!(out, "use arcstr::{{ArcStr, literal}};").unwrap();
    writeln!(out, "use metamodelica::*;").unwrap();
    writeln!(out, "use metamodelica::Result;\n").unwrap();
    for u in &p.uses {
        let c = p
            .tpl_crates
            .get(u)
            .cloned()
            .or_else(|| idx.crates.get(u).cloned())
            .or_else(|| idx.packages.get(u).map(|pk| pk.krate.clone()));
        match c {
            Some(c) if c == p.krate => writeln!(out, "use crate::{u};").unwrap(),
            Some(c) => writeln!(out, "use {c}::{u};").unwrap(),
            None => return Err(vec![format!("{pkg}: no crate known for package {u}")]),
        }
    }
    out.push('\n');
    out.push_str(&body);
    Ok((p.krate.clone(), out))
}
